"""Pack web/index.html into Core/Src/web_page.c as a gzip byte array.

Run after editing index.html:  python web/make_page.py
The rover serves the bytes with "Content-Encoding: gzip".
"""
import gzip
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
FW = HERE.parent
html = (HERE / "index.html").read_text(encoding="utf-8")

# Drop indentation and blank lines; keep line breaks so the script stays valid.
lines = [ln.strip() for ln in html.splitlines()]
packed = "\n".join(ln for ln in lines if ln).encode("utf-8")
gz = gzip.compress(packed, compresslevel=9, mtime=0)

rows = []
for i in range(0, len(gz), 16):
    rows.append("    " + ", ".join(f"0x{b:02X}" for b in gz[i:i + 16]) + ",")

c_src = f"""/* Generated by web/make_page.py from web/index.html. Do not edit by hand. */
/* {len(packed)} bytes of HTML, {len(gz)} bytes gzipped */
#include "web_page.h"

const uint8_t g_web_page_gz[] = {{
{chr(10).join(rows)}
}};

const uint16_t g_web_page_gz_len = (uint16_t)sizeof(g_web_page_gz);
"""
(FW / "Core" / "Src" / "web_page.c").write_text(c_src, encoding="ascii")

h_src = """/* Rover control page, gzip-compressed (see web/make_page.py) */
#ifndef __WEB_PAGE_H
#define __WEB_PAGE_H

#include <stdint.h>

extern const uint8_t g_web_page_gz[];
extern const uint16_t g_web_page_gz_len;

#endif /* __WEB_PAGE_H */
"""
(FW / "Core" / "Inc" / "web_page.h").write_text(h_src, encoding="ascii")
print(f"web_page.c: {len(packed)} bytes HTML -> {len(gz)} bytes gzip")
